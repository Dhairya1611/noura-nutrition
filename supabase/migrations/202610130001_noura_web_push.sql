create table if not exists public.noura_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique check (char_length(endpoint) between 20 and 4096),
  p256dh text not null check (char_length(p256dh) between 20 and 512),
  auth text not null check (char_length(auth) between 8 and 256),
  timezone text not null default 'UTC' check (char_length(timezone) between 1 and 100),
  user_agent text not null default '',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create index if not exists noura_push_subscriptions_user_id_idx
  on public.noura_push_subscriptions(user_id);

alter table public.noura_push_subscriptions enable row level security;
revoke all on table public.noura_push_subscriptions from anon, authenticated;

create table if not exists public.noura_push_deliveries (
  id bigint generated by default as identity primary key,
  subscription_id bigint not null references public.noura_push_subscriptions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  reminder_id text not null,
  local_date date not null,
  scheduled_for timestamptz not null,
  status text not null default 'claimed' check (status in ('claimed', 'sent', 'failed')),
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  sent_at timestamptz,
  unique (subscription_id, reminder_id, local_date)
);

create index if not exists noura_push_deliveries_created_at_idx
  on public.noura_push_deliveries(created_at);

alter table public.noura_push_deliveries enable row level security;
revoke all on table public.noura_push_deliveries from anon, authenticated;

create or replace function public.register_noura_push_subscription(
  push_endpoint text,
  push_p256dh text,
  push_auth text,
  push_timezone text,
  push_user_agent text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  owner_id uuid := auth.uid();
  verified_timezone text;
  subscription_id bigint;
begin
  if owner_id is null then
    raise exception 'Authentication is required';
  end if;
  if char_length(push_endpoint) not between 20 and 4096
    or char_length(push_p256dh) not between 20 and 512
    or char_length(push_auth) not between 8 and 256 then
    raise exception 'Invalid push subscription';
  end if;

  select name into verified_timezone
  from pg_timezone_names
  where name = coalesce(nullif(push_timezone, ''), 'UTC')
  limit 1;
  verified_timezone := coalesce(verified_timezone, 'UTC');

  insert into public.noura_push_subscriptions (
    user_id, endpoint, p256dh, auth, timezone, user_agent, enabled, last_seen_at
  ) values (
    owner_id, push_endpoint, push_p256dh, push_auth, verified_timezone,
    left(coalesce(push_user_agent, ''), 500), true, now()
  )
  on conflict (endpoint) do update set
    user_id = excluded.user_id,
    p256dh = excluded.p256dh,
    auth = excluded.auth,
    timezone = excluded.timezone,
    user_agent = excluded.user_agent,
    enabled = true,
    updated_at = now(),
    last_seen_at = now()
  returning id into subscription_id;

  return subscription_id;
end;
$$;

revoke all on function public.register_noura_push_subscription(text, text, text, text, text) from public, anon;
grant execute on function public.register_noura_push_subscription(text, text, text, text, text) to authenticated;

create or replace function public.unregister_noura_push_subscription(push_endpoint text)
returns void
language sql
security definer
set search_path = public, auth
as $$
  delete from public.noura_push_subscriptions
  where endpoint = push_endpoint and user_id = auth.uid();
$$;

revoke all on function public.unregister_noura_push_subscription(text) from public, anon;
grant execute on function public.unregister_noura_push_subscription(text) to authenticated;

create or replace function public.claim_noura_due_reminders()
returns table (
  delivery_id bigint,
  subscription_id bigint,
  user_id uuid,
  endpoint text,
  p256dh text,
  auth text,
  reminder_id text,
  reminder_label text,
  scheduled_for timestamptz
)
language sql
security definer
set search_path = public
as $$
  with expanded as (
    select
      subscription.id as subscription_id,
      subscription.user_id,
      subscription.endpoint,
      subscription.p256dh,
      subscription.auth,
      reminder.item ->> 'id' as reminder_id,
      coalesce(nullif(reminder.item ->> 'label', ''), 'meal') as reminder_label,
      (now() at time zone subscription.timezone)::date as local_date,
      (
        (now() at time zone subscription.timezone)::date
        + (reminder.item ->> 'time')::time
      ) at time zone subscription.timezone as scheduled_for
    from public.noura_push_subscriptions as subscription
    join public.noura_user_data as user_data on user_data.user_id = subscription.user_id
    cross join lateral jsonb_array_elements(user_data.reminders) as reminder(item)
    where subscription.enabled
      and reminder.item ->> 'enabled' = 'true'
      and reminder.item ->> 'time' ~ '^(?:[01][0-9]|2[0-3]):[0-5][0-9]$'
      and coalesce(reminder.item ->> 'id', '') <> ''
  ),
  due as (
    select * from expanded
    where expanded.scheduled_for <= now()
      and expanded.scheduled_for > now() - interval '2 minutes'
  ),
  claimed as (
    insert into public.noura_push_deliveries (
      subscription_id, user_id, reminder_id, local_date, scheduled_for
    )
    select due.subscription_id, due.user_id, due.reminder_id, due.local_date, due.scheduled_for
    from due
    on conflict (subscription_id, reminder_id, local_date) do nothing
    returning id, noura_push_deliveries.subscription_id, noura_push_deliveries.user_id,
      noura_push_deliveries.reminder_id, noura_push_deliveries.scheduled_for
  )
  select claimed.id, claimed.subscription_id, claimed.user_id, due.endpoint, due.p256dh,
    due.auth, claimed.reminder_id, due.reminder_label, claimed.scheduled_for
  from claimed
  join due on due.subscription_id = claimed.subscription_id
    and due.user_id = claimed.user_id
    and due.reminder_id = claimed.reminder_id
    and due.scheduled_for = claimed.scheduled_for;
$$;

revoke all on function public.claim_noura_due_reminders() from public, anon, authenticated;
grant execute on function public.claim_noura_due_reminders() to service_role;

